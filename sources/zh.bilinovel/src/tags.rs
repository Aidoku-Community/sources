/// The id of a genre given as an id or as its name.
pub fn tag_id(value: &str) -> Option<&'static str> {
	let value = value.trim();
	TAGS.iter()
		.find(|(id, name)| *id == value || *name == value)
		.map(|(id, _)| *id)
}
