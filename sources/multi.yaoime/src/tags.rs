static RULES: Lazy<[(&str, Regex); 24]> = Lazy::new(|| {
	TAG_RULES.map(|(group, pattern)| (group, Regex::new(&["(?i)", pattern].concat()).unwrap()))
});

// The group the site's panel files a tag under; it compares names lowercased, spaces collapsed.
pub fn group(name: &str) -> &'static str {
	let name = name
		.split_whitespace()
		.collect::<Vec<_>>()
		.join(" ")
		.to_lowercase();
	NAMED_TAGS
		.iter()
		.find(|(_, names)| names.iter().any(|named| named.to_lowercase() == name))
		.map(|(group, _)| *group)
		.or_else(|| {
			RULES
				.iter()
				.find(|(_, rule)| rule.is_match(&name))
				.map(|(group, _)| *group)
		})
		.unwrap_or("other")
}

